#define VMSVGA3D_STALL(cmd) \
  { (cmd), 1, VMSVGA3D_COMMAND_STALL, NULL, #cmd }
#define VMSVGA3D_DISCARD(cmd, type) \
  { (cmd), sizeof(type) / sizeof(uint32_t) + 1, \
    VMSVGA3D_COMMAND_DISCARD, NULL, #cmd }
#define VMSVGA3D_DISCARD_SIZED(cmd, type) \
  { (cmd), \
    (sizeof(SVGA3dCmdSize) + sizeof(type)) / sizeof(uint32_t) + 1, \
    VMSVGA3D_COMMAND_DISCARD, NULL, #cmd }

